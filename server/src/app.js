import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import mongoSanitize from 'express-mongo-sanitize';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import { env } from './config/env.js';
import routes from './routes/index.js';
import { originGuard } from './middleware/auth.js';
import { errorHandler,notFound } from './middleware/error.js';
const app=express();
app.disable('x-powered-by');app.set('trust proxy',1);app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));app.use(cors({origin(origin,callback){if(!origin||env.origins.includes(origin))return callback(null,true);return callback(new Error('Origin is not allowed by CORS'));},credentials:true}));app.use(express.json({limit:'1mb'}));app.use(express.urlencoded({extended:false,limit:'1mb'}));app.use(cookieParser());app.use(mongoSanitize());app.use(morgan(env.NODE_ENV==='production'?'combined':'dev'));app.use(originGuard);app.use('/api/v1',rateLimit({windowMs:60*1000,limit:180,standardHeaders:'draft-7',legacyHeaders:false}));app.use('/api/v1',routes);app.use(notFound);app.use(errorHandler);export default app;
